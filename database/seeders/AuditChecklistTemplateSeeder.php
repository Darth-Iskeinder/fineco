/**
 * Стандарт чек-листа для аудита — справочные данные, а не демо.
 * Стандарт один: он подставляется в каждый новый аудит без выбора руками,
 * а неприменимые к клиенту пункты аудитор помечает статусом «Не применимо».
 * Идемпотентно: пункты пересоздаются под шаблон при каждом запуске.
 *
 *   php artisan db:seed --class=AuditChecklistTemplateSeeder
