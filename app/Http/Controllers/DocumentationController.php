<?php

namespace App\Http\Controllers;

use Illuminate\Support\Str;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;

/**
 * Справка по системе: как что работает, своими словами.
 *
 * Пишется для того, кто в системе работает, а не для нас: язык экрана, а не
 * кода. Ни имён таблиц, ни полей, ни консольных команд — то, что читатель
 * всё равно не сможет применить, ему только мешает. Текст лежит в repo рядом
 * с кодом (`resources/docs`), и правка поведения должна ехать одним коммитом
 * с правкой страницы — иначе справка начнёт врать, а это хуже, чем её
 * отсутствие.
 *
 * Страница открыта без входа, как витрина: в базу не ходит, ссылок внутрь
 * системы не даёт, показывать гостю ей нечего, кроме собственного текста.
 * От поисковиков закрыта — это справка для своих, а не реклама.
 */
class DocumentationController extends Controller
{
    /**
     * Разделы документации. Порядок и названия повторяют левое меню системы:
     * человек ищет справку там же, где привык видеть сам раздел. «Настройки»
     * стоят внизу отдельной группой, как и в меню.
     *
     * ready = false: раздел ещё не написан. Показываем в оглавлении серым,
     * чтобы было видно, чего не хватает, и не выглядело, будто про это забыли.
     */
    private const SECTIONS = [
        'employees' => [
            'title'   => 'Сотрудники',
            'summary' => 'Как завести человека, чем главбух отличается от бухгалтера и кто у кого принимает работу.',
            'ready'   => true,
        ],
        'clients' => [
            'title'   => 'Клиенты',
            'summary' => 'Что писать в карточке клиента, зачем нужны признаки и филиалы, как начинается и заканчивается обслуживание.',
            'ready'   => false,
        ],
        'smeta' => [
            'title'   => 'БухСмета',
            'summary' => 'Как собрать смету клиенту, из чего складывается сумма и когда по строкам пойдут задачи.',
            'ready'   => true,
        ],
        'buhtasks' => [
            'title'   => 'БухЗадачник',
            'summary' => 'Откуда в списке берутся задачи месяца, что считается просрочкой и как задача проходит проверку.',
            'ready'   => false,
        ],
        'audit' => [
            'title'   => 'Аудит',
            'summary' => 'Как проверить работу по клиенту за период: чек-лист, замечания и итог проверки.',
            'ready'   => false,
        ],
        'catalog' => [
            'title'   => 'Бизнес-процессы',
            'summary' => 'Настройки → Бизнес процессы: как завести работу, которую фирма делает клиентам, и что означает каждое поле карточки.',
            'ready'   => true,
            'group'   => 'Администрирование',
        ],
    ];

    /** Оглавление. */
    public function index()
    {
        return view('docs.index', [
            'sections' => self::SECTIONS,
        ]);
    }

    /** Раздел. Slug берём только из списка выше — чужой путь сюда не пролезет. */
    public function show(string $section)
    {
        $meta = self::SECTIONS[$section] ?? null;

        if (!$meta || !$meta['ready']) {
            throw new NotFoundHttpException('Такого раздела документации нет');
        }

        $path = resource_path("docs/kubik/{$section}.md");

        if (!is_file($path)) {
            throw new NotFoundHttpException('Текст раздела не найден');
        }

        return view('docs.section', [
            'sections' => self::SECTIONS,
            'current'  => $section,
            'meta'     => $meta,
            'body'     => Str::markdown(file_get_contents($path)),
        ]);
    }
}
