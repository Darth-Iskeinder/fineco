<?php

namespace App\Support;

/**
 * Кыргызский номер телефона: приведение к 9 цифрам и обратно к читаемому виду.
 *
 * Форма отдаёт национальные 9 цифр — код страны в ней не поле, а подпись у
 * рамки. Но в поле попадает и то, что человек вставил из мессенджера: с +996,
 * со скобками, с ведущим нулём (так номер набирают внутри страны). Всё это один
 * и тот же номер, поэтому лишнее снимаем здесь, до валидации, а не отбиваем
 * ошибкой — иначе вставка из буфера каждый раз оборачивается ручным набором.
 *
 * Хранение — в том же виде, что даёт маска в карточке сотрудника
 * (+996 (705) 664-746): владелец фирмы — такой же сотрудник, и его номер
 * открывается в той же карточке.
 */
class KgPhone
{
    /** Национальные цифры номера: без кода страны, без ведущего нуля. Пусто → null. */
    public static function digits(?string $raw): ?string
    {
        $digits = preg_replace('/\D/', '', (string) $raw);

        if ($digits === '') {
            return null;
        }

        // Лишнее в начале узнаём по длине, а не по самим цифрам: у операторов
        // есть коды 99X, и «996 123 456» — это девятизначный номер целиком, а не
        // код страны с остатком. Резать 996 вслепую значило бы ломать такие номера.
        if (strlen($digits) > 9 && str_starts_with($digits, '996')) {
            $digits = substr($digits, 3);
        }

        // Ведущий ноль — набор внутри страны (0705...), номер тот же.
        if (strlen($digits) > 9 && str_starts_with($digits, '0')) {
            $digits = substr($digits, 1);
        }

        return $digits;
    }

    /** Читаемый вид для хранения и показа. Ждёт уже проверенные 9 цифр. */
    public static function format(string $digits): string
    {
        return sprintf(
            '+996 (%s) %s-%s',
            substr($digits, 0, 3),
            substr($digits, 3, 3),
            substr($digits, 6, 3),
        );
    }
}
